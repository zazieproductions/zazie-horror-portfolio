/**
 * tools/resolve-conflicts.test.mjs
 * -----------------------------------------------------------------------------
 * Unit tests for the automatic conflict resolver's decision logic.
 *
 * The resolver is allowed to commit build output and nothing else, so these
 * tests pin the two ways that promise can break: a path git quotes or renames
 * being misread, and pre-existing build drift being swept into a merge commit.
 *
 *   node --test tools/resolve-conflicts.test.mjs
 */

import assert from 'node:assert/strict';
import { test } from 'node:test';

import {
  COMMENT_MARKER,
  changedPaths,
  hasConflictMarkers,
  isHashedAsset,
  isOffLimits,
  parsePorcelainZ,
  planCommit,
  renderComment,
} from './resolve-conflicts.mjs';

const snapshotOf = (entries) =>
  new Map(entries.map(([filePath, hash, status = ' M']) => [filePath, { status, hash }]));

test('parsePorcelainZ keeps paths with spaces and rename sources intact', () => {
  const text = [' M work/the dark awaits.html', 'R  item-new.css', 'item-old.css', '?? notes.txt', ''].join('\0');
  assert.deepEqual(parsePorcelainZ(text), [
    { status: ' M', path: 'work/the dark awaits.html' },
    { status: 'R ', path: 'item-new.css', from: 'item-old.css' },
    { status: '??', path: 'notes.txt' },
  ]);
});

test('parsePorcelainZ ignores truncated records', () => {
  assert.deepEqual(parsePorcelainZ('M\0\0'), []);
});

test('isOffLimits protects every hand-authored tree', () => {
  for (const filePath of [
    '.github/workflows/deploy.yml',
    '.github/CODEOWNERS',
    'src/data/cues.ts',
    'scripts/prerender.mjs',
    'tools/headers.mjs',
    'docs/architecture/system-map.md',
    'README.md',
    'package.json',
    'package-lock.json',
    'home-src/build.mjs',
    'store-src/build.sh',
    'legal-src/build.sh',
    '.aislop/config.yml',
    '.git/config',
  ]) {
    assert.equal(isOffLimits(filePath), true, `${filePath} must require a human`);
  }
  for (const filePath of [
    'sitemap.xml',
    'robots.txt',
    'llms.txt',
    'llms-full.txt',
    '_redirects',
    'sw.js',
    'work/eclipsed.html',
    'store/eclipsed.html',
    'index-11ae0e31.js',
  ]) {
    assert.equal(isOffLimits(filePath), false, `${filePath} is build output`);
  }
});

test('isHashedAsset matches root-level bundles only', () => {
  for (const filePath of ['index-11ae0e31.js', 'item-L0PUZNzP.css', 'legal-c623083a.js', 'inquiry-d8cba1f7.css']) {
    assert.equal(isHashedAsset(filePath), true, filePath);
  }
  for (const filePath of ['sw.js', 'index.html', 'sitemap.xml', 'work/eclipsed.html', 'audio/cue.mp3']) {
    assert.equal(isHashedAsset(filePath), false, filePath);
  }
});

test('hasConflictMarkers sees real markers, not prose about them', () => {
  assert.equal(hasConflictMarkers('<<<<<<< HEAD\n<p>a</p>\n=======\n<p>b</p>\n>>>>>>> origin/main\n'), true);
  assert.equal(hasConflictMarkers('<p>a footnote</p>\n<!-- kept ======= on purpose? -->\n'), false);
  assert.equal(hasConflictMarkers('===== a heading underline in Markdown'), false);
});

test('planCommit commits conflicts and merge-induced churn, never HEAD drift', () => {
  const baseline = snapshotOf([
    ['legal-c623083a.js', 'drift-deleted', ' D'],
    ['404.html', 'drift-404', ' M'],
    ['.gitignore', 'gitignore', ' M'],
  ]);
  const after = snapshotOf([
    ['legal-c623083a.js', 'drift-deleted', ' D'],
    ['404.html', 'drift-404', ' M'],
    ['.gitignore', 'gitignore-changed', ' M'],
    ['sitemap.xml', 'merged-sitemap', ' M'],
    ['sw.js', 'merged-sw', ' M'],
    ['index-aaaa1111.js', 'new-bundle', '??'],
  ]);

  const { staged, skipped } = planCommit({
    conflicts: ['sitemap.xml', 'sw.js'],
    baseline,
    after,
  });

  assert.deepEqual(
    staged.map((entry) => entry.path),
    ['sitemap.xml', 'sw.js', 'index-aaaa1111.js'],
  );
  assert.equal(staged[0].reason, 'conflicted generated file, regenerated by the build');
  assert.equal(staged[2].reason, 'generated file created by the merge');
  assert.deepEqual(
    skipped.map((entry) => entry.path).sort(),
    ['.gitignore', '404.html', 'legal-c623083a.js'],
  );
  assert.match(skipped.find((entry) => entry.path === '.gitignore').reason, /off-limits/);
  assert.match(skipped.find((entry) => entry.path === '404.html').reason, /pre-existing build drift/);
});

test('planCommit stages a file whose bytes the merged build changed', () => {
  const baseline = snapshotOf([['llms.txt', 'before']]);
  const after = snapshotOf([['llms.txt', 'after']]);
  const { staged } = planCommit({ conflicts: [], baseline, after });
  assert.deepEqual(staged.map((entry) => entry.path), ['llms.txt']);
  assert.match(staged[0].reason, /rewritten for the merged sources/);
});

test('planCommit stages nothing when the merged build reproduces HEAD', () => {
  const baseline = snapshotOf([['sitemap.xml', 'same']]);
  const after = snapshotOf([['sitemap.xml', 'same']]);
  assert.deepEqual(planCommit({ conflicts: [], baseline, after }).staged, []);
});

test('changedPaths compares content hashes, not status letters', () => {
  const before = snapshotOf([
    ['sitemap.xml', 'old'],
    ['sw.js', 'sw'],
  ]);
  const after = snapshotOf([
    ['sitemap.xml', 'new'],
    ['sw.js', 'sw'],
    ['item-zz.png', 'asset'],
  ]);
  assert.deepEqual(changedPaths(before, after), ['sitemap.xml', 'item-zz.png']);
});

test('renderComment reports a resolution with provenance and validation', () => {
  const comment = renderComment({
    status: 'resolved',
    base: { ref: 'main', shortSha: 'abc1234' },
    head: { ref: 'work' },
    conflicts: ['sitemap.xml'],
    staged: [
      { path: 'sitemap.xml' },
      { path: 'sw.js' },
      { path: 'llms.txt' },
    ],
    skipped: [{ path: '404.html' }],
    commit: { shortSha: 'def5678' },
  });
  assert.ok(comment.startsWith(COMMENT_MARKER));
  assert.match(comment, /Merge conflicts resolved automatically/);
  assert.match(comment, /\| `sitemap\.xml` \| rebuilt by `npm run build` \|/);
  assert.match(comment, /2 other regenerated files/);
  assert.match(comment, /byte-identical when rebuilt/);
  assert.match(comment, /known-limitations\.md/);
});

test('renderComment hands source conflicts back with exact paths', () => {
  const comment = renderComment({
    status: 'manual',
    base: { ref: 'main' },
    head: { ref: 'work' },
    conflicts: ['src/data/cues.ts', 'docs/architecture/routing.md'],
    reason: 'Hand-authored files conflict.',
  });
  assert.match(comment, /need a human/);
  assert.match(comment, /- `src\/data\/cues\.ts`/);
  assert.match(comment, /git fetch origin main && git merge origin\/main/);
});

test('renderComment explains a failed run and promises no commit', () => {
  const comment = renderComment({
    status: 'error',
    base: { ref: 'main' },
    head: { ref: 'work' },
    conflicts: [],
    reason: 'working tree is dirty',
    buildTail: ['npm ERR! missing script'],
  });
  assert.match(comment, /could not run/);
  assert.match(comment, /working tree is dirty/);
  assert.match(comment, /npm ERR! missing script/);
  assert.match(comment, /Nothing was committed/);
});
