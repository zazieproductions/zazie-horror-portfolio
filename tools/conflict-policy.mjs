#!/usr/bin/env node
/**
 * tools/conflict-policy.mjs
 * -----------------------------------------------------------------------------
 * The decisions behind the automatic merge-conflict resolver, with no git and
 * no file system in the way: which paths a robot may touch, which porcelain
 * statuses mean what, what a resolution may commit, and what the PR comment
 * says. `tools/resolve-conflicts.mjs` adds the git plumbing.
 *
 * The asymmetry is the point. This repository commits its generated output
 * (AGENTS.md), so two branches that edit different sources still collide on
 * `sitemap.xml`, `llms.txt`, `sw.js` and the hub pages. Those conflicts have
 * exactly one correct answer: whatever the build writes from the merged
 * sources. Source conflicts do not: two people (or agents) disagree about
 * content, and picking a side deletes somebody's work. So generated output is
 * resolved and everything else is reported.
 *
 * No dependencies.
 * -----------------------------------------------------------------------------
 */

/**
 * Paths whose content is a decision rather than a derivation. Even when a build
 * step writes one of them, an automatic merge must not choose between two
 * humans' intent.
 */
export const OFF_LIMITS = [
  /^\.git\//,
  /^\.github\//,
  /^\.aislop\//,
  /^docs\//,
  /^src\//,
  /^scripts\//,
  /^tools\//,
  /^home-src\//,
  /^store-src\//,
  /^legal-src\//,
  /^package(-lock)?\.json$/,
  /\.md$/,
  // Repository configuration: editable by humans, never by a merge robot.
  /^\.gitignore$/,
  /^\.nojekyll$/,
  /^_headers$/,
  /^server\.mjs$/,
  /^tsconfig\.json$/,
  /^vite\.config\.ts$/,
];

/** Root-level content-hashed bundles emitted by vite and the build scripts. */
export const HASHED_ASSET = /^[\w-]+-[A-Za-z0-9_-]{6,16}\.(?:js|css)$/;

export const CONFLICT_MARKER = /^(?:<{7}(?: .*)?|={7}|>{7}(?: .*)?)$/m;

/** Identifies the sticky comment this workflow owns on a pull request. */
export const COMMENT_MARKER = '<!-- auto-resolve-conflicts -->';

export function isOffLimits(filePath) {
  return OFF_LIMITS.some((re) => re.test(filePath));
}

export function isHashedAsset(filePath) {
  return !filePath.includes('/') && HASHED_ASSET.test(filePath);
}

export function hasConflictMarkers(text) {
  return CONFLICT_MARKER.test(text);
}

/**
 * `git status --porcelain=v1 -z` records: "XY path\0" and, for renames and
 * copies, "XY new\0old\0". Paths are never quoted in -z output, so a naive
 * line split corrupts any path with a space.
 */
export function parsePorcelainZ(text) {
  const fields = text.split('\0');
  const entries = [];
  for (let i = 0; i < fields.length; i += 1) {
    const record = fields[i];
    if (record.length < 4) continue;
    const status = record.slice(0, 2);
    const entry = { status, path: record.slice(3) };
    if (status[0] === 'R' || status[0] === 'C') entry.from = fields[(i += 1)];
    entries.push(entry);
  }
  return entries;
}

/**
 * Decide what a resolution may commit.
 *
 *   baseline  Map<path, {status, hash}>  build run at HEAD (pre-merge)
 *   after     Map<path, {status, hash}>  build run on the merged tree
 *   conflicts paths git reported as unmerged
 *
 * A path is committed when it conflicted, when the merged build created it, or
 * when the merged build produced different bytes than the HEAD build did. A
 * path the HEAD build already churned identically is pre-existing drift (see
 * docs/project/known-limitations.md) and is left alone, so a resolution cannot
 * sweep up a hundred unrelated rehashed files.
 */
export function planCommit({ conflicts, baseline, after }) {
  const conflicted = new Set(conflicts);
  const staged = [];
  const skipped = [];
  for (const [filePath, state] of after) {
    const entry = { path: filePath, status: state.status, from: state.from, hash: state.hash };
    if (isOffLimits(filePath)) {
      skipped.push({ ...entry, reason: 'off-limits path' });
    } else if (conflicted.has(filePath)) {
      staged.push({ ...entry, reason: 'conflicted generated file, regenerated by the build' });
    } else if (!baseline.has(filePath)) {
      staged.push({ ...entry, reason: 'generated file created by the merge' });
    } else if (baseline.get(filePath).hash !== state.hash) {
      staged.push({ ...entry, reason: 'generated file rewritten for the merged sources' });
    } else {
      skipped.push({ ...entry, reason: 'pre-existing build drift at HEAD, left untouched' });
    }
  }
  return { staged, skipped };
}

/** Paths whose bytes changed between two snapshots, i.e. what the build rewrote. */
export function changedPaths(before, after) {
  const changed = [];
  for (const [filePath, state] of after) {
    if (before.get(filePath)?.hash !== state.hash) changed.push(filePath);
  }
  return changed;
}

function plural(count, noun) {
  return `${count} ${noun}${count === 1 ? '' : 's'}`;
}

function resolvableNote() {
  return 'The next push to this branch rebuilds and re-tests normally. If a *source* file conflicts later, this stops and asks instead of choosing a side.';
}

function renderResolved(report, lines) {
  const dryRun = report.dryRun === true;
  const title =
    report.status === 'resolved' ? '### Merge conflicts resolved automatically' : '### Branch brought up to date';
  lines.push(
    title,
    '',
    dryRun
      ? `Dry run: \`${report.base.ref}\` (\`${report.base.shortSha}\`) resolves cleanly against \`${report.head.ref}\`. Nothing was committed.`
      : `Base \`${report.base.ref}\` (\`${report.base.shortSha}\`) was merged into \`${report.head.ref}\` and pushed as \`${report.commit.shortSha}\`.`,
    '',
  );

  if (report.status === 'resolved') {
    lines.push(
      'Every conflict was in committed build output. Those files are regenerated from the merged sources, never hand-merged:',
      '',
      '| File | How it was resolved |',
      '|---|---|',
      ...report.conflicts.map((filePath) => `| \`${filePath}\` | rebuilt by \`npm run build\` |`),
      '',
    );
    const alsoStaged = report.staged.length - report.conflicts.length;
    if (alsoStaged > 0) {
      lines.push(
        `Also committed: ${plural(alsoStaged, 'other regenerated file')} whose content the merged sources changed.`,
        '',
      );
    }
  }

  lines.push(
    'Validation on this run: `npm run build` succeeded twice, no conflict markers remain, and the resolved files are byte-identical when rebuilt.',
    '',
  );
  if (report.skipped.length) {
    lines.push(
      `Left alone: ${plural(report.skipped.length, 'file')} of pre-existing build drift at HEAD (documented in \`docs/project/known-limitations.md\`), so this commit contains only merge-related churn.`,
      '',
    );
  }
  lines.push(resolvableNote());
}

function renderManual(report, lines) {
  const needsDecision = report.needsDecision?.length ? report.needsDecision : report.conflicts;
  const regenerable = report.regenerable ?? [];
  lines.push(
    '### Merge conflicts need a human',
    '',
    `\`${report.base.ref}\` conflicts with \`${report.head.ref}\`. Nothing was auto-merged, because these need your decision:`,
    '',
    ...needsDecision.map((filePath) => `- \`${filePath}\``),
    '',
  );
  if (regenerable.length) {
    lines.push(
      'Also conflicting, but committed build output — `npm run build` rewrites these from the merged sources, so do not hand-edit them:',
      '',
      ...regenerable.map((filePath) => `- \`${filePath}\``),
      '',
    );
  }
  lines.push(
    report.reason,
    '',
    'Resolve locally, then let the build write the generated output:',
    '',
    '```bash',
    `git fetch origin ${report.base.ref} && git merge origin/${report.base.ref}`,
    '# edit the files above',
    'npm run build',
    'git add -A && git commit',
    '```',
    '',
    'Re-run *Auto-resolve merge conflicts* (or add the `resolve-conflicts` label) after resolving to check that the generated output is consistent again.',
  );
}

function renderFailure(report, lines) {
  lines.push(
    '### Automatic conflict resolution could not run',
    '',
    `Status: \`${report.status}\`.`,
    '',
    report.reason,
  );
  if (report.buildTail?.length) lines.push('', '```', ...report.buildTail.slice(-25), '```');
  lines.push('', 'Nothing was committed; the branch is unchanged.');
}

/**
 * The PR comment, in the same voice as the other workflows: what happened, what
 * it cost, and what the reader still has to do.
 */
export function renderComment(report) {
  const byStatus = {
    resolved: renderResolved,
    'merged-clean': renderResolved,
    manual: renderManual,
  };
  const render = byStatus[report.status] ?? renderFailure;
  const lines = [COMMENT_MARKER, ''];
  render(report, lines);
  return `${lines.join('\n')}\n`;
}
