#!/usr/bin/env node
/**
 * tools/generate-redirects.mjs
 * -----------------------------------------------------------------------------
 * Regenerates the flat item `.html` -> slashless canonical redirect rules in
 * `_redirects`, and verifies them in --check mode.
 *
 * CANONICAL URL POLICY (enforced here and by tools/live-route-audit.mjs):
 *   Every page has exactly ONE canonical, extensionless, slashless URL
 *   (root "/" excepted), advertised by sitemap.xml, the page's
 *   <link rel="canonical"> and the Link: rel="canonical" header in _headers.
 *   Every other spelling of that page must consolidate onto the canonical:
 *
 *     * .html alias files  -> 308 to the slashless canonical
 *                               (legacy hub aliases keep a hand-written 301;
 *                                flat item aliases are generated below).
 *     * retired routes     -> 301 to their replacement.
 *
 * Cloudflare Pages serves static files at their exact path and does NOT
 * automatically redirect .html to the extensionless route, so each .html
 * alias needs an explicit rule here. Without one, the edge serves the .html
 * file with HTTP 200 alongside its slashless canonical -- duplicate content
 * and a live-route-audit failure (the audit expects 308 -> canonical).
 *
 * The flat-item block below is generated from the real item files
 * (work/, reel/, store/): one 308 rule per item .html file, sorted by path.
 * Legacy hub aliases (/work.html -> /work etc.) and retired routes are
 * hand-written 301 rules.
 *
 *   node tools/generate-redirects.mjs            # write/refresh _redirects
 *   node tools/generate-redirects.mjs --check    # verify parity, write nothing
 *
 * --check is run by the build; a drifted _redirects fails pre-flight before
 * anything reaches the edge. Exit 0 = item rules match the item files.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REDIRECTS = path.join(ROOT, '_redirects');
const MARKER = '# --- generated: flat item .html -> slashless canonical (308) ---';
const REGEN_NOTE = '# Regenerate: node tools/generate-redirects.mjs  (do not hand-edit this block)';

/** Hub directories that have a real <section>/index.html and a root <section>.html twin. */
const HUB_SECTIONS = ['work', 'reel', 'store'];

/**
 * Hand-written legacy rules (301): retired routes and hub .html aliases.
 * Kept in the file's existing order; only this block is hand-edited.
 */
const LEGACY = [
  '/index.html / 301',
  '/work.html /work 301',
  '/reel.html /reel 301',
  '/composer.html /#about 301',
  '/process.html /process 301',
  '/contact /#contact 301',
  '/contact/ /#contact 301',
  '/contact.html /#contact 301',
  '# /composer is retired (2026-10-29): the standalone biography page read as',
  '# bloat, so the route folds into section 01 on the homepage, like /contact.',
  '/composer /#about 301',
  '/composer/ /#about 301',
  '/hire-a-composer.html /hire-a-composer 301',
  '/how-to-hire-a-horror-composer.html /how-to-hire-a-horror-composer 301',
  '/sound-design.html /sound-design 301',
  '/game-scoring.html /game-scoring 301',
  '/store.html /store 301',
  '/legal.html /legal 301',
  '/faq.html /faq 301',
  '/terms.html /terms 301',
  '/privacy.html /privacy 301',
  '/licensing.html /licensing 301',
  '/purchases.html /purchases 301',
  '/accessibility.html /accessibility 301',
  '/sitemap.html /sitemap 301',
  '/hiring-a-horror-composer /how-to-hire-a-horror-composer 301',
  '/hiring-a-horror-composer/ /how-to-hire-a-horror-composer 301',
];

const HEADER = `# Cloudflare Pages redirect rules — canonical URL consolidation
#
# Canonical URL policy: every page has exactly ONE canonical, extensionless,
# slashless URL (root "/" excepted), advertised by sitemap.xml, the page's
# <link rel="canonical"> and the Link: rel="canonical" header in _headers.
# Every other spelling of that page must consolidate onto the canonical:
#
#   * .html alias files  -> 308 to the slashless canonical (legacy hub
#     aliases keep an explicit hand-written 301; flat item aliases are
#     generated below).
#   * retired routes     -> 301 to their replacement.
#
# Cloudflare Pages serves static files at their exact path and does NOT
# automatically redirect .html to the extensionless route, so each .html
# alias needs an explicit rule here. Without one the edge serves the .html
# file with HTTP 200 alongside its slashless canonical -- duplicate content
# and a live-route-audit failure (the audit contract expects 308 -> canonical
# for every .html alias). The flat-item block below is generated by
# tools/generate-redirects.mjs from the real item files; do not hand-edit it.
# A build that adds, removes or renames an item must regenerate and commit
# _redirects in the same pull request.
#
# Note: _redirects only supports redirect/rewrite status codes (200, 301,
# 302, 303, 307, 308). Do NOT add 404 status rules here -- Cloudflare Pages
# rejects them and natively serves /404.html with HTTP status 404 for any
# unmatched path (a real, noindex 404).
`;

/** One `from to 308` rule per real flat item .html file, sorted by path. */
function itemRules() {
  const rules = [];
  for (const section of HUB_SECTIONS) {
    const dir = path.join(ROOT, section);
    if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) continue;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith('.html') || entry.name === 'index.html') continue;
      rules.push(`/${section}/${entry.name} /${section}/${entry.name.slice(0, -'.html'.length)} 308`);
    }
  }
  return rules.sort();
}

function generate() {
  const items = itemRules();
  const lines = [
    HEADER.replace(/\n$/, ''),
    '',
    '# --- legacy / hand-written rules (301; keep sorted) ---',
    ...LEGACY,
    '',
    MARKER,
    REGEN_NOTE,
    ...items,
    '',
  ];
  return lines.join('\n') + '\n';
}

/** Current _redirects content, or null if it has never been generated. */
function currentContent() {
  if (!fs.existsSync(REDIRECTS)) return null;
  return fs.readFileSync(REDIRECTS, 'utf8');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const check = process.argv.includes('--check');
  const generated = generate();
  const current = currentContent();

  if (check) {
    if (current === null || current !== generated) {
      console.log('generate-redirects: FAIL — _redirects is stale (run: node tools/generate-redirects.mjs)');
      process.exit(1);
    }
    console.log(`generate-redirects: ${itemRules().length} item .html redirect rule(s) current in _redirects`);
    process.exit(0);
  }

  fs.writeFileSync(REDIRECTS, generated);
  console.log(`generate-redirects: ${itemRules().length} item .html redirect rule(s) written to _redirects`);
  process.exit(0);
}
