export interface QuoteInput {
  /** Scored music in minutes. Not film runtime. Rounded up to whole minutes. */
  scoredMinutes: number;
  /** Approximate number of cues. Undefined or 0 means "not sure yet": the package allowance applies. */
  cueCount?: number;
  complexity: ComplexityId;
  deadline: DeadlineId;
  /** Additional revision rounds requested beyond the package's included rounds. */
  extraRevisionRounds: number;
  licence: LicenceId;
}

export interface EstimateQuote {
  readonly kind: 'estimate';
  readonly nonbinding: true;
  readonly packageId: EstimatePackageId;
  readonly packageName: string;
  readonly scoredMinutes: number;
  /** The cue count the estimate assumes: the number entered, or the package allowance if none was. */
  readonly cueCount: number;
  readonly cueAllowance: number;
  readonly includedRevisionRounds: number;
  readonly extraRevisionRounds: number;
  /** The commission fee range, before any additional revision rounds. */
  readonly commissionLow: number;
  readonly commissionHigh: number;
  /** The fee range, including any additional revision rounds requested. */
  readonly low: number;
  readonly high: number;
  /** Charge for one additional revision round, at each end of the range. */
  readonly revisionRoundLow: number;
  readonly revisionRoundHigh: number;
  /** Items the range does not include. Empty for a complete estimate. */
  readonly quotedSeparately: readonly string[];
  readonly factors: readonly { readonly label: string; readonly value: string }[];
}

export interface CustomQuote {
  readonly kind: 'custom';
  readonly nonbinding: true;
  readonly reason: 'long-form';
  readonly packageId: 'feature';
  readonly indicativeMinimum: number;
  readonly message: string;
}

export type Quote = EstimateQuote | CustomQuote;

const clamp = (value: number, min: number, max: number): number => Math.min(max, Math.max(min, value));

export function packageById(id: PackageId): PricingPackage {
  const found = PACKAGES.find((p) => p.id === id);
  if (!found) throw new Error(`unknown package ${id}`);
  return found;
}

export function complexityById(id: ComplexityId) {
  return COMPLEXITY.find((c) => c.id === id) ?? COMPLEXITY[0];
}

export function deadlineById(id: DeadlineId) {
  return DEADLINES.find((d) => d.id === id) ?? DEADLINES[0];
}

export function licenceById(id: LicenceId) {
  return LICENCES.find((l) => l.id === id) ?? LICENCES[0];
}

/** Estimator package for a whole number of scored minutes, or null above the long-form threshold. */
export function estimatePackageFor(minutes: number): PricingPackage | null {
  for (const pkg of PACKAGES) {
    if (pkg.minutes && minutes >= pkg.minutes.min && minutes <= pkg.minutes.max) return pkg;
  }
  return null;
}

/**
 * The starting fee for a package at a given number of scored minutes, before the
 * complexity and schedule multipliers. Linear within the package.
 */
export function startingFeeAt(pkg: PricingPackage, minutes: number): number {
  if (!pkg.minutes || pkg.startingFee === null || pkg.perExtraMinute === null) {
    throw new Error(`${pkg.id} has no starting fee`);
  }
  return pkg.startingFee + pkg.perExtraMinute * (minutes - pkg.minutes.min);
}

/** The published "from" figure at the package minimum. */
export function publishedFrom(pkg: PricingPackage): number | null {
  return pkg.startingFee;
}

/** The public price label, e.g. "From $250", "Custom quotation". */
export function priceLabel(pkg: PricingPackage): string {
  if (pkg.display === 'custom' || pkg.startingFee === null) return 'Custom quotation';
  return `From ${usd(pkg.startingFee)}`;
}

/** Whole-dollar formatting used everywhere a price appears. */
export function usd(amount: number): string {
  return '$' + Math.round(amount).toLocaleString('en-US');
}

export function roundEstimate(amount: number): number {
  return Math.round(amount / ROUND_TO) * ROUND_TO;
}

/** The charge for one additional revision round, given the commission fee it applies to. */
export function revisionRoundFee(commissionFee: number): number {
  return Math.max(REVISION_FEE_MINIMUM, Math.round(commissionFee * REVISION_FEE_RATE));
}

/**
 * Indicative estimate. Pure and deterministic: the same input always gives the same
 * range on the homepage, on /services, on /contact and in the browser.
 *
 *   commission fee (low)  = max(MINIMUM_FEE,
 *                               (startingFee + perExtraMinute x (minutes - min))
 *                               x complexity x schedule)            -> rounded to $25
 *   commission fee (high) = commission fee (low) x (1 + RANGE_SPREAD) -> rounded to $25
 *   each additional round = max($75, 10% of the commission fee at that end)
 *   total                 = commission fee + extra rounds x additional round
 *
 * Cues within the package allowance and the standard licence are included. Cues
 * above the allowance and any rights beyond the standard licence are listed in
 * `quotedSeparately`; they are never priced here.
 */
export function quote(input: QuoteInput): Quote {
  const requested = Number.isFinite(input.scoredMinutes) ? Math.ceil(input.scoredMinutes) : 1;
  if (requested > LONG_FORM_THRESHOLD_MINUTES) {
    return {
      kind: 'custom',
      nonbinding: true,
      reason: 'long-form',
      packageId: 'feature',
      indicativeMinimum: FEATURE_MINIMUM,
      message: `Scores over ${LONG_FORM_THRESHOLD_MINUTES} scored minutes, and multi-part or experimental work, are quoted individually after a cut has been reviewed. The indicative minimum for substantial scoring projects is ${usd(FEATURE_MINIMUM)}. A single scene or cue from a feature is commissioned through Individual Scene Scoring.`,
    };
  }

  const minutes = clamp(requested, 1, LONG_FORM_THRESHOLD_MINUTES);
  const pkg = estimatePackageFor(minutes);
  if (!pkg || !pkg.minutes || pkg.cueAllowance === null || pkg.revisionRoundsIncluded === null) {
    throw new Error(`no estimate package for ${minutes} minutes`);
  }

  const complexity = complexityById(input.complexity);
  const deadline = deadlineById(input.deadline);
  const unrounded = Math.max(MINIMUM_FEE, startingFeeAt(pkg, minutes) * complexity.multiplier * deadline.multiplier);
  const commissionLow = roundEstimate(unrounded);
  const commissionHigh = roundEstimate(unrounded * (1 + RANGE_SPREAD));

  const cueRequested = Math.round(input.cueCount ?? 0);
  const cueCount = cueRequested > 0 ? clamp(cueRequested, 1, MAX_CUES) : pkg.cueAllowance;
  const extraCues = Math.max(0, cueCount - pkg.cueAllowance);

  const extraRounds = clamp(Math.round(input.extraRevisionRounds) || 0, 0, MAX_EXTRA_REVISION_ROUNDS);
  const roundLow = revisionRoundFee(commissionLow);
  const roundHigh = revisionRoundFee(commissionHigh);

  const low = roundEstimate(commissionLow + extraRounds * roundLow);
  const high = roundEstimate(commissionHigh + extraRounds * roundHigh);

  const licence = licenceById(input.licence);
  const quotedSeparately: string[] = [];
  if (extraCues > 0) {
    quotedSeparately.push(`${extraCues} ${extraCues === 1 ? 'cue' : 'cues'} above the ${pkg.cueAllowance} included in ${pkg.name}: composed and quoted individually.`);
  }
  if (!licence.included) {
    quotedSeparately.push(`${licence.label}: quoted separately in a written agreement. Not included in this range.`);
  }

  const roundsWord = (n: number) => (n === 1 ? 'round' : 'rounds');
  const factors: { label: string; value: string }[] = [
    { label: 'Package', value: `${pkg.name} (${pkg.guarantee})` },
    { label: 'Scored music', value: `${minutes} ${minutes === 1 ? 'minute' : 'minutes'} of finished music` },
    {
      label: 'Cues',
      value: extraCues > 0
        ? `${cueCount} cues: ${pkg.cueAllowance} included; ${extraCues} more quoted individually`
        : `${cueCount} ${cueCount === 1 ? 'cue' : 'cues'}, within the ${pkg.cueAllowance} included`,
    },
    {
      label: 'Musical complexity',
      value: complexity.multiplier === 1 ? `${complexity.label} (no change)` : `${complexity.label} (adds ${Math.round((complexity.multiplier - 1) * 100)}%)`,
    },
    {
      label: 'Schedule',
      value: deadline.multiplier === 1 ? `${deadline.label} (no change)` : `${deadline.label} (adds ${Math.round((deadline.multiplier - 1) * 100)}%)`,
    },
    {
      label: 'Revisions',
      value: extraRounds === 0
        ? `${pkg.revisionRoundsIncluded} consolidated ${roundsWord(pkg.revisionRoundsIncluded)} included`
        : `${pkg.revisionRoundsIncluded} consolidated ${roundsWord(pkg.revisionRoundsIncluded)} included, plus ${extraRounds} additional ${roundsWord(extraRounds)} at ${usd(roundLow)} to ${usd(roundHigh)} each (greater of ${usd(REVISION_FEE_MINIMUM)} or 10% of the fee)`,
    },
    {
      label: 'Rights',
      value: licence.included ? `${licence.label} (included)` : `${licence.label}: quoted separately`,
    },
  ];

  return {
    kind: 'estimate',
    nonbinding: true,
    packageId: pkg.id as EstimatePackageId,
    packageName: pkg.name,
    scoredMinutes: minutes,
    cueCount,
    cueAllowance: pkg.cueAllowance,
    includedRevisionRounds: pkg.revisionRoundsIncluded,
    extraRevisionRounds: extraRounds,
    commissionLow,
    commissionHigh,
    low,
    high,
    revisionRoundLow: roundLow,
    revisionRoundHigh: roundHigh,
    quotedSeparately,
    factors,
  };
}

