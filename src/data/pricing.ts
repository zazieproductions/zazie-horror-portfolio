/**
 * src/data/pricing.ts
 * ----------------------------------------------------------------------------
 * The single source of truth for every fee, package boundary, modifier, revision
 * allowance and estimate rule published on horror.zazieproductions.com.
 *
 * Nothing else in the repository types a price by hand:
 *
 *   - static pages carry {{zp:...}} tokens (or <!--v:...--> values) that
 *     scripts/sync-pricing.mjs fills from this module;
 *   - marker blocks (<!--zp:packages-->, <!--zp:estimator-->, ...) are rendered
 *     from src/lib/pricing-markup.ts by the same script;
 *   - the homepage island and its budget list are generated by
 *     home-src/build.mjs from the same markup;
 *   - the browser estimator (src/estimator/main.ts) calls quote() below, the same
 *     function the build uses for the default state on every page;
 *   - tools/pricing.test.mjs fails the build when a published figure or rule
 *     drifts from these definitions.
 *
 * All amounts are US dollars.
 *
 * ----------------------------------------------------------------------------
 * COMMERCIAL MODEL (approved owner brief, 2026-10-16)
 *
 *   Scope is priced by SCORED MUSIC MINUTES: the finished original music the
 *   studio composes. It is never priced by the runtime of the film. A 90-minute
 *   feature may need 4 scored minutes; a 6-minute short may need 9.
 *
 *   Each package has a STARTING FEE and a GUARANTEED MAXIMUM of music:
 *
 *     starting fee        the "From" price: a simple scope at the package's
 *                         minimum scored minutes, standard complexity, standard
 *                         schedule.
 *     guaranteed maximum  the most music the package covers. Music above it moves
 *                         the commission to the next package.
 *
 *   Within a package, each scored minute above the minimum adds `perExtraMinute`.
 *   Bands join without gaps or overlap: a longer score never costs less than a
 *   shorter one, and no single extra minute produces a jump of more than about
 *   30% (see tools/pricing.test.mjs).
 *
 *   Musical complexity (density, instrumentation, construction) and schedule
 *   (deadline) multiply the commission fee. Revision rounds beyond the package's
 *   included rounds are charged per round. Cues beyond the package's cue allowance,
 *   and rights beyond the standard project licence, are quoted individually: they
 *   are never priced by formula here.
 *
 * STATUS: prices approved by the owner for publication. Legal documents (terms,
 * licensing, LEGAL.md, RATIFY.md) still conflict with the rights and payment
 * positions below. See COMMERCIAL-OVERHAUL.md section 3 before deployment.
 * ----------------------------------------------------------------------------
 */

